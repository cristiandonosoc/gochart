//go:embed runtime.rs.template
var kRuntime string

func (m *model) generate(metadata *common.Metadata) string {
	w := &writer{}

	m.writeHeader(w, metadata)
	m.writeIds(w)
	m.writeEvent(w)
	m.writeChart(w)
	m.writeDelegate(w)
	m.writeApi(w)
	m.writeTree(w)
	m.writeTables(w)
	m.writeTreeOps(w)
	m.writeCallbacks(w)
	m.writeHandlers(w)
	w.line("")
	w.raw(kRuntime)

	return w.b.String()
}

// derives returns the derive attribute with |base| and the extra derives of the gochart. Extra
// derives that are already in |base| (eg. "Hash" for the id enums) are skipped.
func (m *model) derives(base ...string) string {
	all := append([]string{}, base...)
	for _, derive := range m.gc.Derives {
		name := derive[strings.LastIndex(derive, ":")+1:]
		duplicate := false
		for _, existing := range all {
			if existing == name {
				duplicate = true
				break
			}
		}
		if !duplicate {
			all = append(all, derive)
		}
	}
	return fmt.Sprintf("#[derive(%s)]", strings.Join(all, ", "))
}

func (m *model) writeHeader(w *writer, metadata *common.Metadata) {
	w.line("// GOCHART_HEADER_START")
	w.line("// File generated by Gochart (https://github.com/cristiandonosoc/gochart)")
	w.line("// DO NOT MODIFY!")
	w.line("//")
	w.line("// $GOCHART_VERSION=%q", metadata.Version)
	w.line("// GOCHART_HEADER_END")
	w.line("//")
	w.line("// Gochart %s. Include this file as a module:", m.gc.Name)
	w.line("//     #[path = \"<prefix>.gochart.rs\"] mod %s;", toSnakeCase(m.gc.Name))
	w.line("// Names in the gochart (data and argument types) are resolved in the parent module.")
	w.line("")
	w.line("#[allow(unused_imports)]")
	w.line("use super::*;")
	w.line("")
}

func (m *model) writeIds(w *writer) {
	idDerives := m.derives("Clone", "Copy", "Debug", "PartialEq", "Eq", "Hash", "PartialOrd", "Ord")

	// StateId.
	w.line("/// Every state of gochart %s.", m.gc.Name)
	w.line("%s", idDerives)
	w.line("#[allow(dead_code)]")
	w.open("pub enum StateId {")
	for _, s := range m.States {
		w.line("%s,", s.Name)
	}
	w.close("}")
	w.line("")
	w.line("#[allow(dead_code)]")
	w.open("impl StateId {")
	w.line("pub const ALL: [StateId; %d] = [%s];", len(m.States), joinMap(m.States, func(s *rustState) string { return "StateId::" + s.Name }))
	w.line("")
	w.open("pub fn name(self) -> &'static str {")
	w.open("match self {")
	for _, s := range m.States {
		w.line("StateId::%s => %q,", s.Name, s.Name)
	}
	w.close("}")
	w.close("}")
	w.line("")
	w.line("/// The parent state, or None for the top level states.")
	w.open("pub fn parent(self) -> Option<StateId> {")
	w.line("rt_parent(self)")
	w.close("}")
	w.line("")
	w.open("pub fn as_leaf(self) -> Option<Leaf> {")
	w.open("match self {")
	for _, s := range m.States {
		if s.IsLeaf() {
			w.line("StateId::%s => Some(Leaf::%s),", s.Name, s.Name)
		}
	}
	if len(m.Leaves) != len(m.States) {
		w.line("_ => None,")
	}
	w.close("}")
	w.close("}")
	w.close("}")
	w.line("")

	// Leaf.
	w.line("/// The leaf states of gochart %s: the ones that can be current.", m.gc.Name)
	w.line("%s", idDerives)
	w.line("#[allow(dead_code)]")
	w.open("pub enum Leaf {")
	for _, s := range m.Leaves {
		w.line("%s,", s.Name)
	}
	w.close("}")
	w.line("")
	w.line("#[allow(dead_code)]")
	w.open("impl Leaf {")
	w.line("pub const ALL: [Leaf; %d] = [%s];", len(m.Leaves), joinMap(m.Leaves, func(s *rustState) string { return "Leaf::" + s.Name }))
	w.line("")
	w.open("pub fn name(self) -> &'static str {")
	w.line("self.state().name()")
	w.close("}")
	w.line("")
	w.open("pub fn state(self) -> StateId {")
	w.open("match self {")
	for _, s := range m.Leaves {
		w.line("Leaf::%s => StateId::%s,", s.Name, s.Name)
	}
	w.close("}")
	w.close("}")
	w.close("}")
	w.line("")
	w.open("impl From<Leaf> for StateId {")
	w.open("fn from(leaf: Leaf) -> StateId {")
	w.line("leaf.state()")
	w.close("}")
	w.close("}")
	w.line("")

	// TriggerId.
	if len(m.Triggers) > 0 {
		w.line("/// Every trigger of gochart %s.", m.gc.Name)
		w.line("%s", idDerives)
		w.line("#[allow(dead_code)]")
		w.open("pub enum TriggerId {")
		for _, t := range m.Triggers {
			w.line("%s,", t.Name)
		}
		w.close("}")
		w.line("")
		w.line("#[allow(dead_code)]")
		w.open("impl TriggerId {")
		w.line("pub const ALL: [TriggerId; %d] = [%s];", len(m.Triggers), joinMap(m.Triggers, func(t *rustTrigger) string { return "TriggerId::" + t.Name }))
		w.line("")
		w.open("pub fn name(self) -> &'static str {")
		w.open("match self {")
		for _, t := range m.Triggers {
			w.line("TriggerId::%s => %q,", t.Name, t.Name)
		}
		w.close("}")
		w.close("}")
		w.close("}")
	} else {
		w.line("/// Gochart %s has no triggers.", m.gc.Name)
		w.line("%s", idDerives)
		w.line("#[allow(dead_code)]")
		w.line("pub enum TriggerId {}")
	}
	w.line("")
}

func (m *model) writeEvent(w *writer) {
	w.line("/// A trigger with its arguments.")
	w.line("#[derive(Clone, Debug)]")
	w.line("#[allow(dead_code)]")
	w.open("pub enum Event {")
	for _, t := range m.Triggers {
		if len(t.Args) == 0 {
			w.line("%s,", t.Name)
			continue
		}
		args := make([]string, 0, len(t.Args))
		for _, arg := range t.Args {
			args = append(args, arg.RustString())
		}
		w.line("%s { %s },", t.Name, strings.Join(args, ", "))
	}
	w.close("}")
	w.line("")
	w.line("#[allow(dead_code)]")
	w.open("impl Event {")
	w.open("pub fn id(&self) -> TriggerId {")
	if len(m.Triggers) == 0 {
		w.line("match *self {}")
	} else {
		w.open("match self {")
		for _, t := range m.Triggers {
			pattern := "Event::" + t.Name
			if len(t.Args) > 0 {
				pattern += " { .. }"
			}
			w.line("%s => TriggerId::%s,", pattern, t.Name)
		}
		w.close("}")
	}
	w.close("}")
	w.close("}")
	w.line("")
}

func (m *model) writeChart(w *writer) {
	w.line("/// The number of parallel regions of the gochart. |Chart::leaves| has one entry per region.")
	w.line("#[allow(dead_code)]")
	w.line("pub const REGION_COUNT: usize = %d;", m.RegionCount)
	w.line("")
	w.line("/// The state of gochart %s: which states are active and their data.", m.gc.Name)
	w.line("///")
	w.line("/// A default chart is inactive. Use |activate| to enter the default states.")
	w.line("%s", m.derives("Clone", "Debug", "Default", "PartialEq", "Eq"))
	w.line("#[allow(dead_code)]")
	w.open("pub struct Chart {")
	w.line("tree: Option<ChartChildren>,")
	w.close("}")
	w.line("")
	w.line("#[allow(dead_code)]")
	w.open("impl Chart {")
	w.open("pub fn is_active(&self) -> bool {")
	w.line("self.tree.is_some()")
	w.close("}")
	w.line("")
	w.line("/// Whether |state| is active (either current or a parent of a current state).")
	w.open("pub fn is_in(&self, state: StateId) -> bool {")
	w.line("rt_is_active(self, state)")
	w.close("}")
	w.line("")
	if m.RegionCount == 1 {
		w.line("/// The current leaf state. Panics if the chart is not active.")
		w.open("pub fn leaf(&self) -> Leaf {")
		w.line("rt_leaves(self)[0].and_then(StateId::as_leaf).expect(\"gochart is not active\")")
		w.close("}")
		w.line("")
	}
	w.line("/// The current leaf state of each parallel region (None for inactive regions).")
	w.open("pub fn leaves(&self) -> [Option<Leaf>; REGION_COUNT] {")
	w.line("rt_leaves(self).map(|state| state.and_then(StateId::as_leaf))")
	w.close("}")

	for _, s := range m.States {
		if !s.HasData() {
			continue
		}
		for _, mode := range []bindMode{
			{mutable: false, mismatch: "return None"},
			{mutable: true, mismatch: "return None"},
		} {
			w.line("")
			name, self := s.Snake, "&self"
			if mode.mutable {
				name, self = s.Snake+"_mut", "&mut self"
			}
			w.line("/// The data of state %s, if it is active.", s.Name)
			w.open("pub fn %s(%s) -> Option<%s%s> {", name, self, mode.ref(), s.DataType)
			w.line("let c = self;")
			bindPath(w, s, mode)
			w.line("Some(%s%s.data)", mode.ref(), nodeVar(s))
			w.close("}")
		}
	}
	w.close("}")
	w.line("")
}

func (m *model) writeDelegate(w *writer) {
	w.line("/// The callbacks of gochart %s. The chart lives in the delegate (see |chart|).", m.gc.Name)
	w.line("///")
	w.line("/// While a trigger is being processed the chart is taken out of the delegate, so |chart| returns")
	w.line("/// an inactive chart during callbacks. Callbacks receive the data of the active states instead.")
	w.line("#[allow(dead_code)]")
	w.open("pub trait Delegate {")
	w.line("/// Where the chart lives.")
	w.line("fn chart(&mut self) -> &mut Chart;")
	for _, method := range m.Methods {
		w.line("")
		w.line("/// %s", method.Doc)
		w.line("%s", method.Declaration())
	}
	w.line("")
	w.line("/// Called after |state| is entered (and its enter reactions ran).")
	w.line("fn on_enter_state(&mut self, _state: StateId) {}")
	w.line("")
	w.line("/// Called after |state| is exited (and its exit reactions ran).")
	w.line("fn on_exit_state(&mut self, _state: StateId) {}")
	w.line("")
	w.line("/// Called after a transition from |from| (None for the gochart level) to |to| entered its")
	w.line("/// states, before the null transitions of the new states are evaluated.")
	w.line("fn on_transition(&mut self, _from: Option<StateId>, _to: StateId, _trigger: Option<TriggerId>) {}")
	w.close("}")
	w.line("")
}

func (m *model) writeApi(w *writer) {
	w.line("/// Enters the default states. The chart must be inactive.")
	w.line("#[allow(dead_code)]")
	w.open("pub fn activate<D: Delegate>(delegate: &mut D) {")
	w.line("let mut c = ::core::mem::take(delegate.chart());")
	w.line("rt_activate(delegate, &mut c);")
	w.line("*delegate.chart() = c;")
	w.close("}")
	w.line("")
	w.line("/// Exits every state. The chart must be active.")
	w.line("#[allow(dead_code)]")
	w.open("pub fn deactivate<D: Delegate>(delegate: &mut D) {")
	w.line("let mut c = ::core::mem::take(delegate.chart());")
	w.line("rt_deactivate(delegate, &mut c);")
	w.line("*delegate.chart() = c;")
	w.close("}")
	w.line("")
	w.line("/// Processes a trigger to completion. Returns whether a state handled it (a transition or a")
	w.line("/// capture whose condition passed). An inactive chart handles nothing.")
	w.line("#[allow(dead_code)]")
	w.open("pub fn dispatch<D: Delegate>(delegate: &mut D, event: Event) -> bool {")
	w.line("let mut c = ::core::mem::take(delegate.chart());")
	w.line("let handled = rt_dispatch(delegate, &mut c, &event);")
	w.line("*delegate.chart() = c;")
	w.line("handled")
	w.close("}")

	for _, t := range m.Triggers {
		w.line("")
		params := []string{"delegate: &mut D"}
		for _, arg := range t.Args {
			params = append(params, arg.RustString())
		}
		event := "Event::" + t.Name
		if len(t.Args) > 0 {
			event += " { " + strings.Join(argNames(t), ", ") + " }"
		}
		w.line("/// Sends trigger %s. Returns whether a state handled it (see |dispatch|).", t.Name)
		w.line("#[allow(dead_code)]")
		w.open("pub fn trigger_%s<D: Delegate>(%s) -> bool {", t.Snake, strings.Join(params, ", "))
		w.line("dispatch(delegate, %s)", event)
		w.close("}")
	}
	w.line("")
}

// Tree types --------------------------------------------------------------------------------------

func (m *model) writeTree(w *writer) {
	w.line("// Tree ---------------------------------------------------------------------------------------------")
	w.line("")
	m.writeChildrenType(w, m.Root)
	for _, s := range m.States {
		m.writeNodeType(w, s)
		if s.HasChildren() {
			m.writeChildrenType(w, s)
		}
	}
}

func (m *model) writeNodeType(w *writer, s *rustState) {
	w.line("#[allow(dead_code)]")
	w.line("%s", m.derives("Clone", "Debug", "PartialEq", "Eq"))
	if !s.HasData() && !s.HasChildren() {
		w.line("struct %s {}", s.NodeType())
		w.line("")
		return
	}
	w.open("struct %s {", s.NodeType())
	if s.HasData() {
		w.line("data: %s,", s.DataType)
	}
	if s.HasChildren() {
		w.line("children: %s,", s.ChildrenType())
	}
	w.close("}")
	w.line("")
}

func (m *model) writeChildrenType(w *writer, s *rustState) {
	w.line("#[allow(dead_code)]")
	w.line("%s", m.derives("Clone", "Debug", "PartialEq", "Eq"))
	if s.IsParallel() {
		// Every region is active at the same time.
		w.open("struct %s {", s.ChildrenType())
		for _, child := range s.Children {
			w.line("%s: Option<%s>,", child.FieldName(), child.NodeType())
		}
		w.close("}")
		w.line("")
		w.line("#[allow(dead_code)]")
		w.open("impl %s {", s.ChildrenType())
		fields := joinMap(s.Children, func(child *rustState) string { return child.FieldName() + ": None" })
		w.line("const VACANT: Self = %s { %s };", s.ChildrenType(), fields)
		w.close("}")
		w.line("")
		return
	}

	w.line("#[allow(non_camel_case_types)]")
	w.open("enum %s {", s.ChildrenType())
	w.line("/// No child is active (only while entering or exiting).")
	w.line("__Vacant,")
	for _, child := range s.Children {
		w.line("%s(%s),", child.Name, child.NodeType())
	}
	w.close("}")
	w.line("")
	w.line("#[allow(dead_code)]")
	w.open("impl %s {", s.ChildrenType())
	w.line("const VACANT: Self = %s::__Vacant;", s.ChildrenType())
	w.close("}")
	w.line("")
}

// Tables ------------------------------------------------------------------------------------------

func (m *model) writeTables(w *writer) {
	w.line("// Tables -------------------------------------------------------------------------------------------")
	w.line("")
	w.line("#[allow(dead_code)]")
	w.line("const RT_STATE_COUNT: usize = %d;", len(m.States))
	w.line("#[allow(dead_code)]")
	w.line("const RT_LEAF_COUNT: usize = %d;", len(m.Leaves))
	w.line("#[allow(dead_code)]")
	w.line("const RT_MAX_DEPTH: usize = %d;", m.MaxDepth)
	w.line("#[allow(dead_code)]")
	w.line("const RT_ANY_LEAF: StateId = StateId::%s;", m.Leaves[0].Name)
	w.line("")

	w.line("#[allow(dead_code)]")
	w.open("fn rt_parent(state: StateId) -> Option<StateId> {")
	w.open("match state {")
	for _, s := range m.States {
		w.line("StateId::%s => %s,", s.Name, s.Parent.OptionId())
	}
	w.close("}")
	w.close("}")
	w.line("")

	w.line("#[allow(dead_code)]")
	w.open("fn rt_children(state: Option<StateId>) -> &'static [StateId] {")
	w.open("match state {")
	for _, s := range m.AllStates() {
		w.line("%s => &[%s],", s.OptionId(), joinMap(s.Children, func(c *rustState) string { return "StateId::" + c.Name }))
	}
	w.close("}")
	w.close("}")
	w.line("")

	w.line("#[allow(dead_code, clippy::match_single_binding)]")
	w.open("fn rt_default_child(state: Option<StateId>) -> Option<StateId> {")
	w.open("match state {")
	for _, s := range m.AllStates() {
		if !s.HasChildren() || s.IsParallel() {
			continue
		}
		w.line("%s => Some(StateId::%s),", s.OptionId(), s.ir.DefaultChild().Name)
	}
	w.line("_ => None,")
	w.close("}")
	w.close("}")
	w.line("")

	w.line("#[allow(dead_code)]")
	w.open("fn rt_is_parallel(state: Option<StateId>) -> bool {")
	var parallel []string
	for _, s := range m.AllStates() {
		if s.IsParallel() {
			parallel = append(parallel, s.OptionId())
		}
	}
	if len(parallel) == 0 {
		w.line("let _ = state;")
		w.line("false")
	} else {
		w.line("matches!(state, %s)", strings.Join(parallel, " | "))
	}
	w.close("}")
	w.line("")

	w.line("#[allow(dead_code)]")
	w.open("fn rt_region(state: StateId) -> usize {")
	w.open("match state {")
	for _, s := range m.States {
		w.line("StateId::%s => %d,", s.Name, s.Region)
	}
	w.close("}")
	w.close("}")
	w.line("")
}

// Tree operations ---------------------------------------------------------------------------------

func (m *model) writeTreeOps(w *writer) {
	w.line("// Tree operations ----------------------------------------------------------------------------------")
	w.line("")

	// rt_is_active.
	w.line("#[allow(dead_code, unused_variables)]")
	w.open("fn rt_is_active(c: &Chart, state: StateId) -> bool {")
	w.open("match state {")
	for _, s := range m.States {
		w.open("StateId::%s => {", s.Name)
		bindPath(w, s, bindMode{mutable: false, mismatch: "return false"})
		w.line("true")
		w.close("}")
	}
	w.close("}")
	w.close("}")
	w.line("")

	// rt_active_child.
	w.line("/// The active child of a non parallel state.")
	w.line("#[allow(dead_code, unused_variables, clippy::match_single_binding)]")
	w.open("fn rt_active_child(c: &Chart, state: Option<StateId>) -> Option<StateId> {")
	w.open("match state {")
	for _, s := range m.AllStates() {
		if !s.HasChildren() || s.IsParallel() {
			continue
		}
		w.open("%s => {", s.OptionId())
		mode := bindMode{mutable: false, mismatch: "return None"}
		bindPath(w, s, mode)
		w.open("match %s {", childrenExpr(s, mode))
		w.line("%s::__Vacant => None,", s.ChildrenType())
		for _, child := range s.Children {
			w.line("%s::%s(_) => Some(StateId::%s),", s.ChildrenType(), child.Name, child.Name)
		}
		w.close("}")
		w.close("}")
	}
	w.line("_ => None,")
	w.close("}")
	w.close("}")
	w.line("")

	// rt_attach.
	w.line("/// Creates the node of |state| (and its data) in its parent, which must be active.")
	w.line("#[allow(dead_code, unused_variables)]")
	w.open("fn rt_attach<D: Delegate>(d: &mut D, c: &mut Chart, state: StateId, event: Option<&Event>) {")
	w.open("match state {")
	for _, s := range m.States {
		w.open("StateId::%s => {", s.Name)
		var fields []string
		if s.HasData() {
			if s.DataDefault {
				w.line("let data: %s = ::core::default::Default::default();", s.DataType)
			} else {
				w.open("let data: %s = {", s.DataType)
				args := bindForData(w, s.AncestorDataPath(), bindMutActive)
				w.line("%s", call("d."+dataMethodName(s), append(args, "event")))
				w.close("};")
			}
			fields = append(fields, "data")
		}
		if s.HasChildren() {
			fields = append(fields, fmt.Sprintf("children: %s::VACANT", s.ChildrenType()))
		}
		w.line("let node = %s { %s };", s.NodeType(), strings.Join(fields, ", "))

		parent := s.Parent
		bindPath(w, parent, bindMutActive)
		if parent.IsParallel() {
			slot := "tree"
			if !parent.isRoot {
				slot = nodeVar(parent) + ".children"
			}
			w.line("debug_assert!(%s.%s.is_none());", slot, s.FieldName())
			w.line("%s.%s = Some(node);", slot, s.FieldName())
		} else {
			slot := "*tree"
			if !parent.isRoot {
				slot = nodeVar(parent) + ".children"
			}
			w.line("debug_assert!(matches!(%s, %s::__Vacant));", slot, parent.ChildrenType())
			w.line("%s = %s::%s(node);", slot, parent.ChildrenType(), s.Name)
		}
		w.close("}")
	}
	w.close("}")
	w.close("}")
	w.line("")

	// rt_detach.
	w.line("/// Removes the node of |state| (and its data) from its parent.")
	w.line("#[allow(dead_code, unused_variables)]")
	w.open("fn rt_detach(c: &mut Chart, state: StateId) {")
	w.open("match state {")
	for _, s := range m.States {
		w.open("StateId::%s => {", s.Name)
		parent := s.Parent
		bindPath(w, parent, bindMutActive)
		if parent.IsParallel() {
			slot := "tree"
			if !parent.isRoot {
				slot = nodeVar(parent) + ".children"
			}
			w.line("%s.%s = None;", slot, s.FieldName())
		} else {
			slot := "*tree"
			if !parent.isRoot {
				slot = nodeVar(parent) + ".children"
			}
			w.line("%s = %s::__Vacant;", slot, parent.ChildrenType())
		}
		w.close("}")
	}
	w.close("}")
	w.close("}")
	w.line("")
}

// Callbacks ---------------------------------------------------------------------------------------

// writeReactionCalls writes the calls of the enter or exit reactions of |s|: first the one
// specific to the trigger (if any), then the default one, as the C++ backend does.
func (m *model) writeReactionCalls(w *writer, s *rustState, kind string) {
	reactions := s.ir.EnterReactions
	if kind == "exit" {
		reactions = s.ir.ExitReactions
	}

	for _, reaction := range reactions {
		if reaction.Trigger == nil {
			continue
		}
		trigger := m.triggerMap[reaction.Trigger]
		w.open("if let Some(%s) = event {", trigger.Pattern())
		args := bindForData(w, s.DataPath(), bindMutActive)
		w.line("%s;", call("d."+reactionMethodName(s, kind, trigger), append(args, trigger.ArgBindings()...)))
		w.close("}")
	}
	for _, reaction := range reactions {
		if reaction.Trigger != nil {
			continue
		}
		w.open("{")
		args := bindForData(w, s.DataPath(), bindMutActive)
		w.line("%s;", call("d."+reactionMethodName(s, kind, nil), args))
		w.close("}")
	}
}

func (m *model) writeCallbacks(w *writer) {
	w.line("// Callbacks ----------------------------------------------------------------------------------------")
	w.line("")

	for _, kind := range []string{"enter", "exit"} {
		hook := "on_enter_state"
		if kind == "exit" {
			hook = "on_exit_state"
		}

		w.line("#[allow(dead_code, unused_variables)]")
		w.open("fn rt_call_%s<D: Delegate>(d: &mut D, c: &mut Chart, state: StateId, event: Option<&Event>) {", kind)
		w.open("match state {")
		for _, s := range m.States {
			w.open("StateId::%s => {", s.Name)
			m.writeReactionCalls(w, s, kind)
			w.close("}")
		}
		w.close("}")
		w.line("d.%s(state);", hook)
		w.close("}")
		w.line("")

		// The root is only entered on activation and exited on deactivation, so only the default
		// reactions apply.
		w.line("#[allow(dead_code, unused_variables)]")
		w.open("fn rt_call_%s_root<D: Delegate>(d: &mut D, c: &mut Chart) {", kind)
		reactions := m.Root.ir.EnterReactions
		if kind == "exit" {
			reactions = m.Root.ir.ExitReactions
		}
		for _, reaction := range reactions {
			if reaction.Trigger == nil {
				w.line("d.%s();", reactionMethodName(m.Root, kind, nil))
			}
		}
		w.close("}")
		w.line("")
	}
}

// Trigger handling --------------------------------------------------------------------------------

// writeTransitionOrCapture writes the evaluation of one transition or capture of |s| for
// |trigger| (nil for null transitions). The written code returns true if it handled the trigger.
func (m *model) writeEntry(w *writer, s *rustState, trigger *rustTrigger, entry *handledEntry) {
	var bindings []string
	eventExpr := "None"
	if trigger != nil {
		bindings = trigger.ArgBindings()
		eventExpr = "Some(event)"
	}

	condition := ""
	if entry.Transition != nil {
		condition = entry.Transition.ConditionCallback
	} else {
		condition = entry.Capture.ConditionCallback
	}

	if condition != "" {
		w.open("let handled = {")
		args := bindForData(w, s.DataPath(), bindRefActive)
		w.line("%s", call("d."+callbackMethodName(s, condition), append(args, bindings...)))
		w.close("};")
		w.open("if handled {")
	} else {
		w.open("{")
	}

	if entry.Transition != nil {
		transition := entry.Transition
		if transition.ActionCallback != "" {
			w.open("{")
			args := bindForData(w, s.DataPath(), bindMutActive)
			w.line("%s;", call("d."+callbackMethodName(s, transition.ActionCallback), append(args, bindings...)))
			w.close("}")
		}
		w.line("rt_transition(d, c, %s, StateId::%s, %s);", s.OptionId(), transition.To.Name, eventExpr)
	} else {
		w.open("{")
		args := bindForData(w, s.DataPath(), bindMutActive)
		w.line("%s;", call("d."+captureMethodName(s, trigger), append(args, bindings...)))
		w.close("}")
	}
	w.line("return true;")
	w.close("}")
}

func (m *model) writeHandlers(w *writer) {
	w.line("// Trigger handling ---------------------------------------------------------------------------------")
	w.line("")

	w.line("/// Offers |event| to |state| (None is the gochart level). Returns whether it was handled.")
	w.line("#[allow(dead_code, unused_variables, unreachable_code, clippy::match_single_binding)]")
	w.open("fn rt_handle<D: Delegate>(d: &mut D, c: &mut Chart, state: Option<StateId>, event: &Event) -> bool {")
	w.open("match (state, event) {")
	for _, s := range m.AllStates() {
		for _, t := range m.Triggers {
			entries := m.HandledEntries(s, t)
			if len(entries) == 0 {
				continue
			}
			w.open("(%s, %s) => {", s.OptionId(), t.Pattern())
			for _, entry := range entries {
				m.writeEntry(w, s, t, entry)
			}
			w.line("false")
			w.close("}")
		}
	}
	w.line("_ => false,")
	w.close("}")
	w.close("}")
	w.line("")

	w.line("/// Evaluates the null transitions of the leaf |state|, which was just entered.")
	w.line("#[allow(dead_code, unused_variables, unreachable_code, clippy::match_single_binding)]")
	w.open("fn rt_null_transitions<D: Delegate>(d: &mut D, c: &mut Chart, state: StateId) -> bool {")
	w.open("match state {")
	for _, s := range m.States {
		nullTransitions := s.ir.GetNullTransitions()
		if len(nullTransitions) == 0 {
			continue
		}
		w.open("StateId::%s => {", s.Name)
		for _, transition := range nullTransitions {
			m.writeEntry(w, s, nil, &handledEntry{Transition: transition})
		}
		w.line("false")
		w.close("}")
	}
	w.line("_ => false,")
	w.close("}")
	w.close("}")
}

func joinMap[T any](items []T, fn func(T) string) string {
	parts := make([]string, 0, len(items))
	for _, item := range items {
		parts = append(parts, fn(item))
	}
	return strings.Join(parts, ", ")
}
